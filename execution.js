(() => {
  "use strict";
  const $ = id => document.getElementById(id);
  const panel = $("executionConsole");
  const runButton = $("runSafeDemo");
  const status = $("executionStatus");
  const log = $("executionLog");
  const planStatus = $("planStatus");
  if (!panel || !runButton || !status || !log || !planStatus) return;

  const PLAN_KEY = "agentverse-ai-engine-v2";
  const LOG_KEY = "agentverse-ai-execution-log-v1";
  let entries = [];
  try {
    const stored = JSON.parse(localStorage.getItem(LOG_KEY) || "[]");
    if (Array.isArray(stored)) entries = stored.slice(0, 20);
  } catch {}

  function getApprovedPlan() {
    try {
      const saved = JSON.parse(localStorage.getItem(PLAN_KEY) || "{}");
      if (!saved || saved.pending || !saved.approvedAt || !saved.plan) return null;
      return saved.plan;
    } catch {
      return null;
    }
  }

  function renderLog() {
    log.replaceChildren();
    entries.slice(0, 8).forEach(entry => {
      const row = document.createElement("div");
      row.className = "execution-log-item";
      const time = document.createElement("time");
      time.textContent = new Date(entry.at).toLocaleString();
      const message = document.createElement("span");
      message.textContent = entry.message;
      row.append(time, message);
      log.append(row);
    });
  }

  function record(message) {
    entries.unshift({ at: new Date().toISOString(), message });
    entries = entries.slice(0, 20);
    try { localStorage.setItem(LOG_KEY, JSON.stringify(entries)); } catch {}
    renderLog();
  }

  function updateAvailability() {
    const approved = getApprovedPlan();
    panel.hidden = !approved;
    if (approved) {
      status.textContent = "APPROVED";
      runButton.disabled = false;
    } else {
      status.textContent = "LOCKED";
      runButton.disabled = true;
    }
  }

  runButton.addEventListener("click", () => {
    const plan = getApprovedPlan();
    if (!plan) {
      status.textContent = "APPROVAL REQUIRED";
      updateAvailability();
      return;
    }

    runButton.disabled = true;
    status.textContent = "RUNNING";
    try {
      const lines = [
        "# AGENTVERSE AI — Approved Execution Playbook",
        "",
        "**Generated locally:** " + new Date().toLocaleString(),
        "**Assigned agent:** " + String(plan.agentKey || "specialist"),
        "**Provider:** " + String(plan.provider || "Google Gemini"),
        "**Model:** " + String(plan.model || "Not recorded"),
        "",
        "## Mission",
        String(plan.mission || "Not provided"),
        "",
        "## Summary",
        String(plan.summary || "No summary provided"),
        "",
        "## Execution steps",
        ...(Array.isArray(plan.steps) ? plan.steps.map((step, index) => (index + 1) + ". " + String(step)) : []),
        "",
        "## Risks to review",
        ...(Array.isArray(plan.risks) && plan.risks.length ? plan.risks.map(item => "- " + String(item)) : ["- No risks were listed by the model."]),
        "",
        "## Human approval requirements",
        ...(Array.isArray(plan.needsHumanApproval) && plan.needsHumanApproval.length ? plan.needsHumanApproval.map(item => "- " + String(item)) : ["- Review all actions before carrying them out."]),
        "",
        "## Expected deliverable",
        String(plan.deliverable || "Not specified"),
        "",
        "---",
        "This file was generated by the local AGENTVERSE AI safe-demo executor. It does not mean the listed steps were carried out."
      ];
      const blob = new Blob([lines.join("\n")], { type: "text/markdown;charset=utf-8" });
      const url = URL.createObjectURL(blob);
      const anchor = document.createElement("a");
      const stamp = new Date().toISOString().replace(/[:.]/g, "-");
      anchor.href = url;
      anchor.download = "agentverse-approved-playbook-" + stamp + ".md";
      document.body.append(anchor);
      anchor.click();
      anchor.remove();
      URL.revokeObjectURL(url);

      status.textContent = "COMPLETED";
      record("Safe demo completed: approved playbook exported as a Markdown file.");
    } catch (error) {
      status.textContent = "FAILED";
      record("Safe demo failed: " + (error && error.message ? error.message : "Unknown browser error."));
    } finally {
      runButton.disabled = false;
    }
  });

  window.addEventListener("storage", event => {
    if (event.key === PLAN_KEY) updateAvailability();
  });
  renderLog();
  updateAvailability();
  $("planMission").addEventListener("click", () => window.setTimeout(updateAvailability, 0));
  $("approvePlan").addEventListener("click", () => window.setTimeout(updateAvailability, 0));
  $("rejectPlan").addEventListener("click", () => window.setTimeout(updateAvailability, 0));
})();
